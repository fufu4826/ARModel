class ReportBuilder(bt.Builder):
    """Figures and tables numbered 1, 2, 3 ... (one report, no chapters)."""

    def figure(self, b, chap):
        self.fig["r"] = self.fig.get("r", 0) + 1
        num = str(self.fig["r"])
        self.blank()
        self.image(self.path(b["image"]), width_cm=b.get("width_cm"), height_cm=b.get("height_cm"))
        par = self.p("", align="center", keep_next=bool(b.get("source")))
        add_run(par, f"ภาพที่ {num}", bold=True)
        add_run(par, " " + b["caption"])
        self.blank()

    def report(self, out, title_lines, blocks):
        self.new_section(number="arabic", restart=1, hide_first=False)
        for line in title_lines:
            self.p(line, align="center", size=20, bold=True, keep_next=True)
        self.blank()
        self.blocks(blocks, "1")
        self.d.save(out)


def table_override(builder):
    """Keep the skill's table renderer, but number tables 1, 2 ... instead of 1.1."""
    original = bt.Builder.table
    counter = {"n": 0}

    def table(self, b, chap):
        original(self, b, chap)
        counter["n"] += 1
        for par in reversed(self.d.paragraphs):
            if par.text.startswith("ตารางที่ "):
                bold = [r for r in par.runs if r.bold]
                bold[0].text = f"ตารางที่ {counter['n']}"
                for r in bold[1:]:
                    r.text = ""
                break
    builder.table = table.__get__(builder)


def item_section(no, title, status, where, adds, figures=(), extra=()):
    blocks = [{"type": "h2", "text": f"{no}. {title}"},
              {"type": "p", "text": f"**สถานะ** {status}"}]
    if where:
        blocks.append({"type": "p", "text": f"**ตำแหน่งที่ปรับปรุง** {where}"})
    if adds:
        blocks.append({"type": "p", "text": "**สิ่งที่ปรับปรุง** มีรายละเอียดดังนี้"})
        blocks.append({"type": "list", "items": adds})
    blocks.extend(extra)
    blocks.extend(figures)
    return blocks


def fig(image, caption, width=None, height=None):
    b = {"type": "figure", "image": os.path.join(IMG, image), "caption": caption, "source": None}
    if width:
        b["width_cm"] = width
    if height:
        b["height_cm"] = height
    return b


